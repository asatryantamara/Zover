/* ===== Mobile nav ===== */
const menuToggle = document.getElementById('menuToggle');
const nav = document.querySelector('.nav');
menuToggle.addEventListener('click',()=>{
  const open = nav.classList.toggle('open');
  menuToggle.classList.toggle('open', open);
  menuToggle.setAttribute('aria-expanded', open);
});
nav.querySelectorAll('a').forEach(a=>a.addEventListener('click',()=>{
  nav.classList.remove('open'); menuToggle.classList.remove('open');
  menuToggle.setAttribute('aria-expanded', false);
}));

/* ===== Gallery lightbox ===== */
const galleryItems = [...document.querySelectorAll('#zardGallery .gallery-item')];
const zardSources = galleryItems.map(b=>b.dataset.src);
const lb = document.getElementById('lightbox');
const lbImg = document.getElementById('lightboxImg');
let lbIndex = 0;
let activeSources = zardSources;
function openLb(i){ lbIndex=(i+activeSources.length)%activeSources.length; lbImg.src=activeSources[lbIndex]; lb.classList.add('open'); lb.setAttribute('aria-hidden','false'); }
function openGallery(srcs,i){ activeSources = srcs; openLb(i||0); }
function closeLb(){ lb.classList.remove('open'); lb.setAttribute('aria-hidden','true'); }
galleryItems.forEach((b,i)=>b.addEventListener('click',()=>openGallery(zardSources,i)));
document.querySelectorAll('.project-card[data-gallery]').forEach(card=>{
  const srcs = card.dataset.gallery.split(',').map(s=>s.trim()).filter(Boolean);
  card.addEventListener('click',()=>openGallery(srcs,0));
});
document.getElementById('lightboxClose').addEventListener('click',closeLb);
document.getElementById('lightboxNext').addEventListener('click',()=>openLb(lbIndex+1));
document.getElementById('lightboxPrev').addEventListener('click',()=>openLb(lbIndex-1));
lb.addEventListener('click',e=>{ if(e.target===lb) closeLb(); });
document.addEventListener('keydown',e=>{
  if(!lb.classList.contains('open')) return;
  if(e.key==='Escape') closeLb();
  if(e.key==='ArrowRight') openLb(lbIndex+1);
  if(e.key==='ArrowLeft') openLb(lbIndex-1);
});

/* ===== Reveal on scroll ===== */
const revealEls = document.querySelectorAll('.section-head, .project-card, .zard-intro, .zard-specs, .gallery, .zard-cta-bar, .about-intro, .point, .contact-card');
revealEls.forEach(el=>el.setAttribute('data-reveal',''));
const io = new IntersectionObserver(entries=>{
  entries.forEach(en=>{ if(en.isIntersecting){ en.target.classList.add('in'); io.unobserve(en.target); } });
},{threshold:.12});
revealEls.forEach(el=>io.observe(el));

